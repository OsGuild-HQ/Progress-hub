"""Render weekly and monthly Guild reports as Markdown."""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from datetime import date

from progress_bot.analysis import MISSING, ContributorWeek, needs_attention
from progress_bot.models import LEVELS, Activity, Contributor, Objective, PullRequest
from progress_bot.weeks import Week, monday_of, mondays_in_month

DIGEST_ITEMS = 3


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def level_name(level: str) -> str:
    return level.capitalize()


def _level_order(c: Contributor) -> tuple[int, str]:
    rank = LEVELS.index(c.profile.level) if c.profile.level in LEVELS else len(LEVELS)
    return rank, c.login.lower()


def file_link(c: Contributor, month: str, depth: int = 2) -> str:
    up = "../" * depth
    return f"{up}contributors/{c.folder.name}/{month}.md"


def pr_links(prs: list[PullRequest], limit: int = 5) -> str:
    shown = [f"[{cell(pr.ref)}]({pr.url})" for pr in prs[:limit]]
    if len(prs) > limit:
        shown.append(f"+{len(prs) - limit} more")
    return ", ".join(shown)


def _bullets(items: list[str], limit: int | None = DIGEST_ITEMS) -> list[str]:
    chosen = items if limit is None else items[:limit]
    lines = [f"  - {item}" for item in chosen]
    if limit is not None and len(items) > limit:
        lines.append(f"  - _…and {len(items) - limit} more in the report_")
    return lines


def _count(activity: Activity | None, attr: str, error: str | None) -> str:
    if error:
        return "?"
    if activity is None:
        return "–"
    return str(len(getattr(activity, attr)))


def _flag_text(cw: ContributorWeek) -> str:
    parts = []
    for flag in cw.flags:
        if flag == MISSING and cw.missing_streak > 1:
            parts.append(f"{MISSING} ({cw.missing_streak} weeks)")
        else:
            parts.append(flag)
    return ", ".join(parts)


@dataclass
class ReportContext:
    generated: date
    github: bool
    llm: bool


def _header(title: str, ctx: ReportContext) -> list[str]:
    sources = ["contributor files"]
    if ctx.github:
        sources.append("the GitHub search API")
    note = (
        f"_Generated by progress-bot on {ctx.generated.isoformat()} from {' and '.join(sources)}."
    )
    if ctx.llm:
        note += " Paragraphs marked **AI-generated** were written by a language model; check them."
    note += " Flags point mentors at people who may need help; they are not scores._"
    return [f"# {title}", "", note, ""]


def weekly_report(results: list[ContributorWeek], week: Week, ctx: ReportContext) -> str:
    results = sorted(results, key=lambda r: _level_order(r.contributor))
    expected = [r for r in results if r.expected]
    reported = [r for r in expected if r.entry is not None]
    by_level: dict[str, int] = defaultdict(int)
    for r in expected:
        by_level[r.contributor.profile.level] += 1

    def total(attr: str) -> str:
        if not ctx.github:
            return "–"
        return str(sum(len(getattr(r.activity, attr)) for r in expected if r.activity))

    level_bits = " · ".join(
        f"{level_name(lvl)}s {by_level[lvl]}" for lvl in LEVELS if by_level.get(lvl)
    )
    lines = _header(f"Guild Weekly Summary — {week.label} ({week.human()})", ctx)
    lines += [
        "## Overview",
        "",
        "| | |",
        "|---|---|",
        f"| Active contributors | {len(expected)}"
        + (f" ({level_bits})" if level_bits else "")
        + " |",
        f"| Reported this week | {len(reported)} / {len(expected)} |",
        f"| PRs opened / merged | {total('opened')} / {total('merged')} |",
        f"| PRs reviewed | {total('reviewed')} |",
        f"| Reporting blockers | {sum(bool(r.entry and r.entry.blockers) for r in expected)} |",
        "",
    ]

    # Needs attention, grouped by mentor.
    lines += ["## Needs attention", ""]
    groups: dict[str, list[ContributorWeek]] = defaultdict(list)
    for r in expected:
        if needs_attention(r):
            mentor = r.contributor.profile.mentor
            groups[f"Mentor @{mentor}" if mentor else "No mentor assigned"].append(r)
    if not groups:
        lines += ["Nothing flagged this week.", ""]
    for heading in sorted(groups, key=lambda h: (h == "No mentor assigned", h.lower())):
        lines += [f"### {heading}", ""]
        for r in groups[heading]:
            detail = ""
            if r.entry and r.entry.blockers:
                detail = f" — “{cell(r.entry.blockers[0])}”"
            elif r.entry and r.entry.support_needed:
                detail = f" — “{cell(r.entry.support_needed[0])}”"
            lines.append(f"- @{r.login}: {_flag_text(r)}{detail}")
        lines.append("")

    # Table.
    lines += [
        "## Contributors",
        "",
        "| Contributor | Level | Report | Objectives | PRs opened | PRs merged | Reviews | Flags |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in expected:
        c = r.contributor
        objectives = f"{r.objectives_done}/{len(r.objectives)}" if r.objectives else "–"
        lines.append(
            "| "
            + " | ".join(
                [
                    f"[@{c.login}]({file_link(c, week.month)})",
                    level_name(c.profile.level),
                    "✓" if r.entry else "✗",
                    objectives,
                    _count(r.activity, "opened", r.github_error),
                    _count(r.activity, "merged", r.github_error),
                    _count(r.activity, "reviewed", r.github_error),
                    cell(_flag_text(r)) or "",
                ]
            )
            + " |"
        )
    inactive = [r for r in results if not r.expected and r.contributor.profile.active is False]
    if inactive:
        names = ", ".join(f"@{r.login}" for r in inactive)
        lines += ["", f"_Inactive, not expected to report: {names}._"]
    lines.append("")

    # Per-contributor digests.
    lines += ["## This week, by contributor", ""]
    for r in expected:
        if r.entry is None and (r.activity is None or r.activity.empty):
            continue
        lines += _digest(r, ctx)
    return "\n".join(lines).rstrip() + "\n"


def _digest(r: ContributorWeek, ctx: ReportContext) -> list[str]:
    c = r.contributor
    mentor = f", mentor @{c.profile.mentor}" if c.profile.mentor else ""
    lines = [f"### @{c.login} — {c.profile.name} ({level_name(c.profile.level)}{mentor})", ""]
    if r.narrative:
        lines += [f"> **AI-generated:** {r.narrative}", ""]
    e = r.entry
    if e is None:
        lines += ["_No report this week._", ""]
    else:
        for title, section in (
            ("Accomplished", "Accomplished"),
            ("Next week", "Next Week"),
            ("Blockers", "Blockers"),
            ("Support needed", "Support Needed"),
        ):
            items = e.items(section)
            if items:
                lines.append(f"- **{title}:**")
                lines += _bullets(items)
    if ctx.github:
        if r.github_error:
            lines.append(f"- **GitHub:** unavailable ({cell(r.github_error)})")
        elif r.activity is not None and not r.activity.empty:
            bits = []
            for label, prs in (
                ("opened", r.activity.opened),
                ("merged", r.activity.merged),
                ("reviewed", r.activity.reviewed),
            ):
                if prs:
                    bits.append(f"{label} {pr_links(prs)}")
            lines.append(f"- **GitHub:** {'; '.join(bits)}")
        if r.unreported:
            lines.append(f"- **On GitHub but not in the report:** {pr_links(r.unreported)}")
    if r.objectives:
        marks = []
        for o in r.objectives:
            links = r.evidence_for(o.id)
            extra = f" ({links} link{'s' if links != 1 else ''} this week)" if links else ""
            marks.append(f"{'✓' if o.done else '☐'} {o.id}{extra}")
        lines.append(f"- **Objectives ({r.week.month}):** {' · '.join(marks)}")
    lines.append("")
    return lines


