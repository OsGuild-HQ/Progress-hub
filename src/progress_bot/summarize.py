@dataclass
class ContributorMonth:
    contributor: Contributor
    month: str
    activity: Activity | None = None
    github_error: str | None = None


def monthly_report(results: list[ContributorMonth], month: str, ctx: ReportContext) -> str:
    results = sorted(results, key=lambda r: _level_order(r.contributor))
    current = monday_of(ctx.generated)
    # Only finished weeks count; the week in progress is not "missed" yet.
    mondays = [m for m in mondays_in_month(month) if m < current]
    lines = _header(f"Guild Monthly Review — {month}", ctx)
    lines += [
        "## Overview",
        "",
        "| Contributor | Level | Weeks reported | Objectives done "
        "| PRs opened | PRs merged | Reviews |",
        "|---|---|---|---|---|---|---|",
    ]
    active = [
        r
        for r in results
        if r.contributor.profile.active
        and r.contributor.first_month is not None
        and r.contributor.first_month <= month
    ]
    for r in active:
        c = r.contributor
        mf = c.month(month)
        weeks = sum(c.week(m) is not None for m in mondays)
        objectives = mf.objectives if mf else []
        done = f"{sum(o.done for o in objectives)}/{len(objectives)}" if objectives else "–"
        lines.append(
            f"| [@{c.login}]({file_link(c, month)}) | {level_name(c.profile.level)} "
            f"| {weeks}/{len(mondays)} | {done} "
            f"| {_count(r.activity, 'opened', r.github_error)} "
            f"| {_count(r.activity, 'merged', r.github_error)} "
            f"| {_count(r.activity, 'reviewed', r.github_error)} |"
        )
    lines += ["", "## By contributor", ""]
    for r in active:
        lines += _month_digest(r, mondays)
    lines += [
        "## For the monthly review",
        "",
        "Mentors and contributors: go through each list above together. Keep, change or drop",
        "the open objectives, and write next month's plan in the next month file.",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def _month_digest(r: ContributorMonth, mondays: list[date]) -> list[str]:
    c = r.contributor
    mf = c.month(r.month)
    lines = [f"### @{c.login} — {c.profile.name}", ""]
    if mf is None:
        return [*lines, "_No plan or reports this month._", ""]
    evidence: dict[str, int] = defaultdict(int)
    blockers: list[str] = []
    learned: list[str] = []
    for w in mf.weeks:
        for ev in w.evidence:
            for tag in ev.objectives:
                evidence[tag] += 1
        blockers += [b for b in w.blockers if b not in blockers]
        learned += [item for item in w.items("Learned") if item not in learned]
    done = [o for o in mf.objectives if o.done]
    open_ = [o for o in mf.objectives if not o.done]

    def objective_line(o: Objective) -> str:
        n = evidence.get(o.id, 0)
        extra = f" — {n} linked PR/issue{'s' if n != 1 else ''}" if n else ""
        return f"  - {o.id}: {o.text}{extra}"

    if done:
        lines.append("- **Completed:**")
        lines += [objective_line(o) for o in done]
    if open_:
        lines.append("- **Still open:**")
        lines += [objective_line(o) for o in open_]
    missing = [m for m in mondays if c.week(m) is None]
    if missing:
        lines.append("- **Weeks without a report:** " + ", ".join(m.isoformat() for m in missing))
    if blockers:
        lines.append("- **Blockers raised:**")
        lines += _bullets(blockers, limit=5)
    if learned:
        lines.append("- **Learned:**")
        lines += _bullets(learned, limit=5)
    if r.activity is not None and r.activity.merged:
        lines.append(f"- **Merged PRs:** {pr_links(r.activity.merged, limit=8)}")
    lines.append("")
    return lines
